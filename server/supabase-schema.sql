-- Run this in the Supabase SQL Editor. Safe to run on a new project or after
-- the earlier local-only schema.

create table if not exists public.transactions (
  id bigint generated by default as identity primary key,
  type text not null check (type in ('exp', 'inc')),
  amount numeric(12, 2) not null check (amount > 0),
  category text not null,
  note text not null default '',
  date date not null
);

-- Existing transaction rows keep their data (and remain unassigned). New rows
-- belong to the signed-in user.
alter table public.transactions
  add column if not exists user_id uuid references auth.users(id) on delete cascade;
alter table public.transactions alter column user_id set default auth.uid();
create index if not exists idx_transactions_date on public.transactions (date desc);
alter table public.transactions enable row level security;
drop policy if exists transactions_owner_access on public.transactions;
create policy transactions_owner_access on public.transactions
  for all to authenticated
  using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));
grant select, insert, update, delete on table public.transactions to authenticated;
grant usage, select on sequence public.transactions_id_seq to authenticated;

-- Per-user budgets use their own table so they don't collide with the old
-- single-user budgets table whose primary key was only the month.
create table if not exists public.monthly_budgets (
  user_id uuid not null references auth.users(id) on delete cascade,
  month text not null check (month ~ '^\d{4}-(0[1-9]|1[0-2])$'),
  amount numeric(12, 2) not null check (amount >= 0),
  primary key (user_id, month)
);
alter table public.monthly_budgets enable row level security;
drop policy if exists monthly_budgets_owner_access on public.monthly_budgets;
create policy monthly_budgets_owner_access on public.monthly_budgets
  for all to authenticated
  using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));
grant select, insert, update, delete on table public.monthly_budgets to authenticated;

-- Monthly recurring bills belong to the signed-in user. Marking a bill paid
-- creates its transaction and updates its paid month in one database transaction.
create table if not exists public.recurring_bills (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  name text not null check (length(trim(name)) between 1 and 60),
  amount numeric(12, 2) not null check (amount > 0),
  category text not null default 'Bills',
  due_day smallint not null check (due_day between 1 and 31),
  active boolean not null default true,
  last_paid_month text check (last_paid_month is null or last_paid_month ~ '^\d{4}-(0[1-9]|1[0-2])$'),
  created_at timestamptz not null default now()
);
create index if not exists idx_recurring_bills_owner on public.recurring_bills (user_id, active, due_day);
alter table public.recurring_bills enable row level security;
drop policy if exists recurring_bills_owner_access on public.recurring_bills;
create policy recurring_bills_owner_access on public.recurring_bills
  for all to authenticated
  using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));
grant select, insert, update, delete on table public.recurring_bills to authenticated;
grant usage, select on sequence public.recurring_bills_id_seq to authenticated;

create or replace function public.record_recurring_bill_payment(p_bill_id bigint, p_month text, p_date date)
returns void
language plpgsql
security invoker
set search_path = public
as $$
declare
  bill public.recurring_bills%rowtype;
begin
  if p_month !~ '^\d{4}-(0[1-9]|1[0-2])$' or to_char(p_date, 'YYYY-MM') <> p_month then
    raise exception 'Payment date must be in the selected month';
  end if;

  select * into bill from public.recurring_bills
  where id = p_bill_id and user_id = auth.uid() and active;
  if not found then
    raise exception 'Bill is unavailable';
  end if;

  if exists (
    select 1 from public.transactions t
    where t.user_id = auth.uid() and t.type = 'exp'
      and t.date >= (p_month || '-01')::date
      and t.date < ((p_month || '-01')::date + interval '1 month')::date
      and left(t.note, length('Bill #' || bill.id || ':')) = 'Bill #' || bill.id || ':'
  ) then
    raise exception 'Bill is already paid this month';
  end if;

  update public.recurring_bills
  set last_paid_month = p_month
  where id = p_bill_id and user_id = auth.uid() and active
    and last_paid_month is distinct from p_month
  returning * into bill;

  if not found then
    raise exception 'Bill is already paid this month or is unavailable';
  end if;

  insert into public.transactions (user_id, type, amount, category, note, date)
  values (auth.uid(), 'exp', bill.amount, bill.category, 'Bill #' || bill.id || ': ' || bill.name, p_date);
end;
$$;
revoke all on function public.record_recurring_bill_payment(bigint, text, date) from public;
grant execute on function public.record_recurring_bill_payment(bigint, text, date) to authenticated;

