-- Public profile images are stored under a folder named for their owner.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('avatars', 'avatars', true, 5242880, array['image/jpeg', 'image/png', 'image/webp'])
on conflict (id) do update set
  public = excluded.public,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists avatars_insert_own on storage.objects;
create policy avatars_insert_own on storage.objects
  for insert to authenticated
  with check (bucket_id = 'avatars' and (storage.foldername(name))[1] = (select auth.uid()::text));

drop policy if exists avatars_delete_own on storage.objects;
create policy avatars_delete_own on storage.objects
  for delete to authenticated
  using (bucket_id = 'avatars' and (storage.foldername(name))[1] = (select auth.uid()::text));

-- Fixed-date installment reminders imported from bill screenshots.
create table if not exists public.installment_reminders (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  name text not null default 'SPayLater installment',
  amount numeric(12, 2) not null check (amount > 0),
  due_date date not null,
  paid boolean not null default false,
  created_at timestamptz not null default now(),
  unique (user_id, name, due_date)
);
create index if not exists idx_installment_reminders_owner_due on public.installment_reminders (user_id, paid, due_date);
alter table public.installment_reminders enable row level security;
drop policy if exists installment_reminders_owner_access on public.installment_reminders;
create policy installment_reminders_owner_access on public.installment_reminders
  for all to authenticated
  using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));
grant select, insert, update, delete on table public.installment_reminders to authenticated;
grant usage, select on sequence public.installment_reminders_id_seq to authenticated;

create or replace function public.record_installment_reminder_payment(p_reminder_id bigint, p_date date)
returns void
language plpgsql
security invoker
set search_path = public
as $$
declare
  reminder public.installment_reminders%rowtype;
begin
  select * into reminder from public.installment_reminders
  where id = p_reminder_id and user_id = auth.uid() and not paid
  for update;
  if not found then
    raise exception 'Installment is already marked paid or unavailable';
  end if;

  update public.installment_reminders set paid = true
  where id = p_reminder_id and user_id = auth.uid();

  insert into public.transactions (user_id, type, amount, category, note, date)
  values (auth.uid(), 'exp', reminder.amount, 'Bills', 'SPayLater installment #' || reminder.id, p_date);
end;
$$;
revoke all on function public.record_installment_reminder_payment(bigint, date) from public;
grant execute on function public.record_installment_reminder_payment(bigint, date) to authenticated;
